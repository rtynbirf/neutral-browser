/// Бинарный поиск глифа по кодпоинту. None = глифа нет (счётчик).
/// ВНИМАНИЕ: шаблон — plain-строка: в Python 3.12 f-строка жрёт "[m".
pub fn lookup(cp: u32) -> Option<&'static Glyph> {
    let mut lo = 0usize;
    let mut hi = GLYPHS.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        if GLYPHS[mid].cp < cp {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if lo < GLYPHS.len() && GLYPHS[lo].cp == cp {
        Some(&GLYPHS[lo])
    } else {
        None
    }
}

/// Ширина продвижения глифа при размере fs: целочисленный масштаб
/// advance*fs/EM с округлением половины вверх (детерминизм без f64).
pub fn advance_of(g: &Glyph, fs: i64) -> i64 {
    (g.adv as i64 * fs + EM / 2) / EM
}

/// Сдвиг baseline от верха ячейки при размере fs (округление вверх).
pub fn ascent_px(fs: i64) -> i64 {
    (ASCENT * fs + EM / 2) / EM
}

/// Глубина baseline до низа ячейки при размере fs (округление вверх).
/// Нужна для CSS half-leading: baseline строки = (h − asc − desc)/2 + asc.
pub fn descent_px(fs: i64) -> i64 {
    (DESCENT * fs + EM / 2) / EM
}
